#!/usr/bin/env python3
"""Build the view-only public copies of the dashboard from team.html.

team.html is the team dashboard and the only file to edit. This writes:

  index.html              The site's front page: the public map. It sits next
                          to data/, so it loads data from the same site.
  public-view/Index.html  The same page for a Google Apps Script web app,
                          which has no data/ folder, so it loads data from the
                          published copy on raw.githubusercontent.com.

The build-public-view workflow runs this on every push to main that changes
team.html, so both copies follow the team dashboard on their own. To run it by
hand, from the repo root:

    python3 scripts/build_public_view.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'team.html'

BANNER = '<!-- GENERATED by scripts/build_public_view.py from team.html. Do not edit this file: edit team.html. -->\n'


def flags(remote_data):
    lines = ['<script>', 'window.PUBLIC_VIEW = true;']
    if remote_data:
        lines.append('window.DATA_REMOTE_FIRST = true;')
    lines.append('</script>')
    return '\n'.join(lines) + '\n'


def build(html, remote_data, for_apps_script):
    if for_apps_script:
        # Apps Script sets the title and viewport itself (Code.gs) and ignores
        # http-equiv cache headers inside the page.
        html = re.sub(r'\s*<meta http-equiv="[^"]*"[^>]*>', '', html)
        html = re.sub(r'\s*<meta name="viewport"[^>]*>', '', html)
    else:
        html = html.replace('<title>NYC Tree Dashboard</title>',
                            '<title>LES Ecology Center Tree Care Map</title>', 1)
    head = re.search(r'<head>\s*', html)
    if not head:
        sys.exit('No <head> in team.html')
    html = html[:head.end()] + flags(remote_data) + html[head.end():]
    doctype = re.match(r'<!DOCTYPE html>\s*', html, re.I)
    if doctype:
        html = html[:doctype.end()] + BANNER + html[doctype.end():]
    return html


def main():
    html = SRC.read_text(encoding='utf-8')
    if 'PUBLIC VIEW MODE' not in html:
        sys.exit('team.html has no PUBLIC VIEW MODE block; nothing to build.')
    outputs = [
        (ROOT / 'index.html', build(html, remote_data=False, for_apps_script=False)),
        (ROOT / 'public-view' / 'Index.html', build(html, remote_data=True, for_apps_script=True)),
    ]
    for path, text in outputs:
        path.parent.mkdir(exist_ok=True)
        path.write_text(text, encoding='utf-8')
        print('Wrote %s (%.2f MB)' % (path.relative_to(ROOT), path.stat().st_size / 1e6))


if __name__ == '__main__':
    main()
