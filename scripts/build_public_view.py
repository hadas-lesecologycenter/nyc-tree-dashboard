#!/usr/bin/env python3
"""Build the view-only public dashboard for Google Apps Script.

Reads index.html and writes public-view/Index.html: the same page with public
view switched on (see PUBLIC VIEW MODE in index.html) and data loaded from the
published copy of data/, since an Apps Script web app has no data/ folder next
to it.

Run from the repo root after any change to index.html:

    python3 scripts/build_public_view.py

Then paste public-view/Index.html into the Apps Script project and deploy a new
version (see PUBLIC_VIEW_SETUP.md).
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'index.html'
OUT = ROOT / 'public-view' / 'Index.html'

FLAGS = ('<script>\n'
         '// Generated by scripts/build_public_view.py. Do not edit; edit index.html and rebuild.\n'
         'window.PUBLIC_VIEW = true;\n'
         'window.DATA_REMOTE_FIRST = true;\n'
         '</script>\n')


def main():
    html = SRC.read_text(encoding='utf-8')
    if 'PUBLIC VIEW MODE' not in html:
        sys.exit('index.html has no PUBLIC VIEW MODE block; nothing to build.')

    # Apps Script sets the title and viewport itself (Code.gs) and ignores
    # http-equiv cache headers inside the page, so drop them here.
    html = re.sub(r'\s*<meta http-equiv="[^"]*"[^>]*>', '', html)
    html = re.sub(r'\s*<meta name="viewport"[^>]*>', '', html)

    head = re.search(r'<head>\s*', html)
    if not head:
        sys.exit('No <head> in index.html')
    html = html[:head.end()] + FLAGS + html[head.end():]

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(html, encoding='utf-8')
    print('Wrote %s (%.2f MB)' % (OUT.relative_to(ROOT), OUT.stat().st_size / 1e6))


if __name__ == '__main__':
    main()
